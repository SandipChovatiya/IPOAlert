import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { StatusBadge, TypeBadge } from "@/components/Badges";
import Calculator from "@/components/Calculator";
import CompanyLogo from "@/components/CompanyLogo";
import SubscriptionChart from "@/components/SubscriptionChart";
import WatchButton from "@/components/WatchButton";
import { getIpoBySlug, subscriptionHistory } from "@/lib/db";
import { fmtDate, fmtIssueSize, fmtPriceBand, inr, parsePriceBand, timing } from "@/lib/format";

export const dynamic = "force-dynamic";

type Props = { params: Promise<{ slug: string }> };

const SLUG_RE = /^[a-z0-9][a-z0-9-_.]{0,127}$/i;

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const ipo = SLUG_RE.test(slug) ? await getIpoBySlug(slug) : null;
  return { title: ipo?.name ?? "IPO not found" };
}

function Fact({ label, value }: { label: string; value: string }) {
  return (
    <div className="card px-4 py-3">
      <dt className="text-xs uppercase tracking-wide text-muted">{label}</dt>
      <dd className="mt-0.5 text-lg font-semibold">{value}</dd>
    </div>
  );
}

function ExtLink({ href, children }: { href: string | null; children: React.ReactNode }) {
  if (!href) return null;
  return (
    <a href={href} target="_blank" rel="noopener noreferrer nofollow" className="btn">
      {children} <span aria-hidden="true">↗</span>
    </a>
  );
}

export default async function IpoPage({ params }: Props) {
  const { slug } = await params;
  if (!SLUG_RE.test(slug)) notFound();
  const ipo = await getIpoBySlug(slug);
  if (!ipo) notFound();

  const history = await subscriptionHistory(ipo.id);
  const band = parsePriceBand(ipo.priceRange);
  const t = timing(ipo);
  const sub = ipo.subscription;
  const gmpEntries = ipo.gmp ? Object.entries(ipo.gmp).filter(([, v]) => ["string", "number"].includes(typeof v)).slice(0, 8) : [];

  return (
    <article className="space-y-8">
      <Link href="/" className="text-sm text-muted hover:text-ink">← All IPOs</Link>

      <header className="flex flex-wrap items-start gap-4">
        <CompanyLogo src={ipo.logo} name={ipo.name} size={64} />
        <div className="min-w-0 flex-1">
          <h1 className="text-2xl font-bold tracking-tight sm:text-3xl">{ipo.name}</h1>
          <div className="mt-2 flex flex-wrap items-center gap-2">
            <StatusBadge status={ipo.status} />
            <TypeBadge type={ipo.type} />
            <span className="text-sm text-muted">{ipo.symbol}</span>
            {t.text ? <span className="text-sm font-medium" style={{ color: t.urgent ? "var(--danger)" : "var(--muted)" }}>{t.text}</span> : null}
          </div>
        </div>
        <WatchButton slug={ipo.slug} name={ipo.name} />
      </header>

      <dl className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Fact label="Price band" value={fmtPriceBand(ipo.priceRange)} />
        <Fact label="Lot size" value={ipo.minQty ? `${ipo.minQty.toLocaleString("en-IN")} shares` : "—"} />
        <Fact label="Min. investment" value={inr(ipo.minAmount)} />
        <Fact label="Issue size" value={fmtIssueSize(ipo.issueSize)} />
        <Fact label="Opens" value={fmtDate(ipo.startDate)} />
        <Fact label="Closes" value={fmtDate(ipo.endDate)} />
        <Fact label="Listing" value={fmtDate(ipo.listingDate)} />
        <Fact label="Listing gain" value={ipo.listingGain || "—"} />
      </dl>

      {ipo.aiSummary ? (
        <section className="card border-l-4 p-5" style={{ borderLeftColor: "var(--accent)" }}>
          <h2 className="text-sm font-semibold text-accent">AI summary</h2>
          <p className="mt-2 whitespace-pre-line leading-relaxed">{ipo.aiSummary}</p>
          <p className="mt-2 text-xs text-muted">Generated by Claude from the data below. Not investment advice.</p>
        </section>
      ) : null}

      <div className="grid gap-6 lg:grid-cols-3">
        <section className="card space-y-4 p-5 lg:col-span-2">
          <h2 className="text-lg font-semibold">Subscription</h2>
          {sub?.timesSubscribed != null ? (
            <>
              <p className="text-4xl font-bold tracking-tight">
                {sub.timesSubscribed.toFixed(2)}<span className="text-xl text-muted">x</span>
              </p>
              <div className="h-2 overflow-hidden rounded-full bg-surface-2">
                <div className="h-full rounded-full bg-open" style={{ width: `${Math.min(100, sub.timesSubscribed * 50)}%` }} />
              </div>
              <p className="text-xs text-muted">
                {sub.noOfsharesBid != null && sub.noOfSharesOffered != null
                  ? `${sub.noOfsharesBid.toLocaleString("en-IN")} bid vs ${sub.noOfSharesOffered.toLocaleString("en-IN")} offered · `
                  : ""}
                as reported by NSE
              </p>
              <SubscriptionChart points={history} />
            </>
          ) : (
            <p className="text-sm text-muted">Subscription data appears once bidding starts.</p>
          )}
        </section>

        <section className="card space-y-3 p-5">
          <h2 className="text-lg font-semibold">Investment calculator</h2>
          {ipo.minQty && band ? (
            <Calculator minQty={ipo.minQty} priceMax={band.max} />
          ) : (
            <p className="text-sm text-muted">Lot size or price band not announced yet.</p>
          )}
        </section>
      </div>

      {ipo.about ? (
        <section className="card p-5">
          <h2 className="text-lg font-semibold">About the company</h2>
          <p className="mt-2 whitespace-pre-line leading-relaxed text-ink/90">{ipo.about}</p>
        </section>
      ) : null}

      {ipo.strengths.length || ipo.risks.length ? (
        <div className="grid gap-6 md:grid-cols-2">
          {ipo.strengths.length ? (
            <section className="card p-5">
              <h2 className="text-lg font-semibold" style={{ color: "var(--open)" }}>Strengths</h2>
              <ul className="mt-3 list-disc space-y-2 pl-5 text-sm leading-relaxed">
                {ipo.strengths.map((s, i) => <li key={i}>{s}</li>)}
              </ul>
            </section>
          ) : null}
          {ipo.risks.length ? (
            <section className="card p-5">
              <h2 className="text-lg font-semibold" style={{ color: "var(--danger)" }}>Risks</h2>
              <ul className="mt-3 list-disc space-y-2 pl-5 text-sm leading-relaxed">
                {ipo.risks.map((s, i) => <li key={i}>{s}</li>)}
              </ul>
            </section>
          ) : null}
        </div>
      ) : null}

      {ipo.schedule.length ? (
        <section className="card p-5">
          <h2 className="text-lg font-semibold">Schedule</h2>
          <ol className="mt-3 space-y-3 border-l-2 border-border pl-5">
            {ipo.schedule.map((s, i) => (
              <li key={i} className="relative">
                <span className="absolute -left-[1.6rem] top-1.5 h-2.5 w-2.5 rounded-full bg-accent" aria-hidden="true" />
                <p className="text-sm font-semibold">{s.event}</p>
                <p className="text-xs text-muted">{fmtDate(s.date)}</p>
              </li>
            ))}
          </ol>
        </section>
      ) : null}

      <section className="card p-5">
        <h2 className="text-lg font-semibold">Grey market premium</h2>
        {gmpEntries.length ? (
          <dl className="mt-3 grid grid-cols-2 gap-3 text-sm sm:grid-cols-4">
            {gmpEntries.map(([k, v]) => (
              <div key={k}>
                <dt className="text-muted">{k}</dt>
                <dd className="font-semibold">{String(v)}</dd>
              </div>
            ))}
          </dl>
        ) : (
          <p className="mt-2 text-sm text-muted">GMP is an optional paid add-on on ipoalerts and isn&apos;t enabled for this account.</p>
        )}
      </section>

      <div className="flex flex-wrap gap-2">
        <ExtLink href={ipo.prospectusUrl}>Prospectus</ExtLink>
        <ExtLink href={ipo.nseInfoUrl}>NSE page</ExtLink>
        <ExtLink href={ipo.infoUrl}>More info</ExtLink>
        {ipo.mediaLinks.slice(0, 5).map((m, i) => (
          <ExtLink key={m} href={m}>Coverage {i + 1}</ExtLink>
        ))}
      </div>
    </article>
  );
}
